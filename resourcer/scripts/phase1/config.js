'use strict';
const path = require('path');
const paths = require('../lib/paths');
const env = require('../lib/env');

function num(name, def) {
  const raw = env.get(name);
  if (raw === undefined) return def;
  const n = Number(raw);
  return Number.isFinite(n) && n >= 0 ? n : def;
}

// Every timing and timeout in one place; the env names are test hooks and operator overrides.
function loadConfig() {
  const sec = (name, def) => num(name, def) * 1000;
  return {
    heartbeatMs: Math.max(50, sec('PHASE1_HEARTBEAT_SEC', 20)),
    pageRetryPauseMs: sec('SCREEN_PAGE_RETRY_PAUSE_SEC', 120),
    settleMs: num('PHASE1_SETTLE_MS', 5000),
    unlockPauseMs: num('PHASE1_UNLOCK_PAUSE_MS', 1500),
    maxConsecutivePageErrors: Math.max(1, Math.floor(num('PHASE1_MAX_CONSECUTIVE_PAGE_ERRORS', 5))),
    incompleteMaxRuns: Math.max(1, Math.floor(num('PHASE1_INCOMPLETE_MAX_RUNS', 3))),
    unlockFailLimit: Math.max(1, Math.floor(num('PHASE1_UNLOCK_FAIL_LIMIT', 5))),
    dbFailLimit: Math.max(1, Math.floor(num('PHASE1_DB_FAIL_LIMIT', 3))),
    screenInputMode: env.get('SCREEN_INPUT_MODE', 'stdin') === 'file' ? 'file' : 'stdin',
    runTimestamp: env.get('PHASE1_RUN_TIMESTAMP') || '',
    timeoutMs: {
      lock: sec('PHASE1_LOCK_TIMEOUT_SEC', 30),
      credits: sec('PHASE1_CREDITS_TIMEOUT_SEC', 180),
      db: sec('PHASE1_DB_TIMEOUT_SEC', 60),
      screenBatch: sec('PHASE1_SCREEN_TIMEOUT_SEC', 1500),
      screenSingle: sec('PHASE1_SINGLE_TIMEOUT_SEC', 330),
      unlock: sec('PHASE1_UNLOCK_TIMEOUT_SEC', 180),
      handoff: sec('PHASE1_HANDOFF_TIMEOUT_SEC', 3900),
      login: sec('PHASE1_LOGIN_TIMEOUT_SEC', 600),
    },
    browserMs: { open: 90000, wait: 90000, eval: 60000, probe: 30000, url: 20000, stateSave: 60000 },
  };
}

