// candidates-db.js lives at the workspace root, every other script under scripts/.
function scriptPath(name) {
  const key = ENV_SCRIPT_PREFIX + name.toUpperCase().replace(/[^A-Z0-9]/g, '_');
  const override = env.get(key);
  if (override) return path.resolve(override);
  if (name === 'candidates-db') return path.join(paths.HOME, 'candidates-db.js');
  return path.join(paths.SCRIPTS, name + '.js');
}

